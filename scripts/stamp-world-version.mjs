// Writes the world cache key from the files it actually guards.
//
// This was a hand-maintained constant tied to one buffer's hash, which broke the first
// time a world file changed that was not that buffer: roadnet.json grew a whole city
// expansion while the version stayed put, so a returning player would have kept the old
// streets until their week-long cache expired. Deriving it from every world file
// removes the manual step and the way it fails.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const files = [
  "game/public/assets/world/highlands-rivers-v1/world.gltf",
  "game/public/assets/world/highlands-rivers-v1/buffers/world-0.bin",
  "game/public/assets/world/highlands-rivers-v1/buffers/world-1.bin",
  "game/public/world/roadnet.json",
];

const digest = createHash("sha256");
const missing = [];
for (const file of files) {
  const path = resolve(root, file);
  if (!existsSync(path)) { missing.push(file); continue; }
  digest.update(file);
  digest.update(readFileSync(path));
}
if (missing.length > 0) throw new Error(`cannot stamp the world: missing ${missing.join(", ")}`);

const version = digest.digest("hex").slice(0, 12);
writeFileSync(resolve(root, "game/src/worldVersion.ts"),
`// Generated by scripts/stamp-world-version.mjs — do not edit by hand.
//
// The cache key for every world asset. World files carry a long cache header on paths
// that never change, so this is what makes a rebuilt world reach a returning player
// instead of waiting out their cache. It covers world.gltf, both buffers and
// roadnet.json, so changing any of them changes the key.
export const WORLD_ASSET_VERSION = "${version}";
`);
console.log(`world version ${version} (over ${files.length} files)`);
